def search_nutrition_knowledge(query: str) -> Dict[str, Any]:
    """
    다이어트 팁, 혈당 관리, 대체 메뉴, 영양 섭취 가이드 지식 베이스를 검색합니다.
    """
    if not query:
        return {"result": "검색어를 입력해주세요."}
        
    query_lower = query.lower()
    matches = []
    
    for item in NUTRITION_KNOWLEDGE_BASE:
        # 키워드 매칭 점수 계산
        score = 0
        for kw in item["keywords"]:
            if kw in query_lower:
                score += 2
        if any(word in item["content"] for word in query_lower.split()):
            score += 1
            
        if score > 0:
            matches.append((score, item))
            
    # 매칭 순으로 정렬
    matches.sort(key=lambda x: x[0], reverse=True)
    
    if matches:
        top_item = matches[0][1]
        return {
            "주제": top_item["topic"],
            "가이드내용": top_item["content"]
        }
        
    # 기본 반환
    return {
        "주제": "일반 다이어트 웰니스 조언",
        "가이드내용": "규칙적인 단백질 섭취와 충분한 수분 보충, 주 3회 이상의 유산소/근력 운동 병행이 가장 지속 가능한 다이어트의 정석입니다."
    }

